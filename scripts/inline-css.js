// Inlines the site CSS into index.html so the first paint needs no extra request
// (fixes Lighthouse "Render-blocking requests" and the HTML -> CSS chain in "Network dependency tree").
//
// Run it after the CSS is built:   npm run build     (build:css -> build:inline -> build:js)
// or on its own:                   npm run build:inline
//
// The CSS lands between the two inline-css markers in index.html. Never edit that block by hand;
// change assets/css/style.css or the Tailwind classes, then run the build again.
// If the markers are missing (for example an older copy of index.html was saved over the file),
// the script finds the two <link rel="stylesheet"> tags and converts them again.
// Other pages keep loading the external, cached CSS files.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const pages = ['index.html'];
const cssFiles = ['assets/css/tailwind.min.css', 'assets/css/style.min.css'];

const START = '<!-- inline-css:start (generated by scripts/inline-css.js from tailwind.min.css + style.min.css. Do not edit by hand: run npm run build) -->';
const END = '<!-- inline-css:end -->';
const markerBlock = /<!-- inline-css:start[\s\S]*?<!-- inline-css:end -->/;
const linkTag = file => new RegExp('[ \\t]*<link rel="stylesheet" href="' + file.replace(/[.]/g, '\\.') + '(?:\\?v=\\d+)?">[ \\t]*\\r?\\n?');
const oldComment = '<!-- Core Design System & Layout Stylesheets (Render-blocking to prevent layout shift & FOUC) -->';
const newComment = '<!-- Core Design System & Layout Stylesheets: inlined below, so the first paint does not wait for a CSS request -->';

const css = cssFiles.map(f => {
  const text = fs.readFileSync(path.join(root, f), 'utf8').trim();
  if (/<\/style/i.test(text)) throw new Error(f + ' contains "</style", which would break the inline <style> block');
  return '/* ' + f + ' */\n' + text;
}).join('\n');

for (const page of pages) {
  const file = path.join(root, page);
  const before = fs.readFileSync(file, 'utf8');
  const eol = before.includes('\r\n') ? '\r\n' : '\n';
  const block = START + eol + '  <style id="site-css">' + eol + css + eol + '  </style>' + eol + '  ' + END;
  let html = before;

  if (markerBlock.test(html)) {
    html = html.replace(markerBlock, () => block);
  } else {
    const first = html.match(linkTag(cssFiles[0]));
    if (!first || cssFiles.some(f => !linkTag(f).test(html))) {
      throw new Error(page + ': neither the inline-css markers nor both <link rel="stylesheet"> tags were found');
    }
    const indent = (first[0].match(/^[ \t]*/) || [''])[0];
    html = html.replace(linkTag(cssFiles[0]), () => indent + block + eol);
    for (const f of cssFiles.slice(1)) html = html.replace(linkTag(f), '');
    html = html.replace(oldComment, newComment);
  }

  if (html !== before) {
    fs.writeFileSync(file, html, 'utf8');
    console.log(page + ': CSS inlined (' + Math.round(css.length / 1024) + ' KB), page is now ' + Math.round(html.length / 1024) + ' KB');
  } else {
    console.log(page + ': already up to date');
  }
}
